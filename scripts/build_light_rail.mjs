// Builds the light rail overlay from Austin Transit Partnership's own
// published map layers.
//
//   node scripts/build_light_rail.mjs            (or: npm run build:rail)
//   node scripts/build_light_rail.mjs --refresh  (download the layers again)
//
// Sources (public ArcGIS feature layers, owner ATP_GIS, no key needed):
//   route     "Light Rail Route"                 .../LRT_Route/FeatureServer/0
//   stations  "Light Rail Stations (Phase 1)"    .../Light_Rail_Map___Abri_WFL1/FeatureServer/0
// The raw downloads are cached in data/_cache/light_rail/ so the build runs
// offline and the file can be checked against what was downloaded.
//
// What is drawn: the Phase 1 line only, the project that received its
// federal Record of Decision in January 2026. One branched line:
// 38th Street down Guadalupe, across downtown and the lake, then south to
// Oltorf and east along Riverside to Yellow Jacket Lane.
//
// What is left out, on purpose:
//   * The route layer's "Priority Extension" and "Future Extension" pieces
//     (airport, Crestview and beyond). They are not funded or scheduled.
//   * The Phase 1 piece labelled "Riverside | Airport Commerce": a short
//     track past the last station with no station on it. (Read here as the
//     track to the maintenance yard; the layer itself does not say.)
//
// Output: data/projectConnect.js (generated; do not edit).

import { readFileSync, writeFileSync, existsSync, mkdirSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import { simplify, lineString, point, pointToLineDistance } from "@turf/turf";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const CACHE = join(ROOT, "data", "_cache", "light_rail");
const OUT = join(ROOT, "data", "projectConnect.js");
const REFRESH = process.argv.includes("--refresh");
const ORG = "https://services7.arcgis.com/BnWSLs6TLD51iZWF/arcgis/rest/services";
const LAYERS = {
  route: `${ORG}/LRT_Route/FeatureServer/0`,
  stations: `${ORG}/Light_Rail_Map___Abri_WFL1/FeatureServer/0`,
};
const TOLERANCE = 0.00002; // degrees, about 2 m: drops points a map this size cannot show
const NOT_PASSENGER = new Set(["Riverside | Airport Commerce"]);

mkdirSync(CACHE, { recursive: true });

/** One layer as { edited, features }, from the cache unless --refresh. */
async function load(name) {
  const file = join(CACHE, `${name}.json`);
  if (existsSync(file) && !REFRESH) return JSON.parse(readFileSync(file, "utf8"));
  const meta = await (await fetch(`${LAYERS[name]}?f=json`)).json();
  const res = await fetch(`${LAYERS[name]}/query?where=1%3D1&outFields=*&outSR=4326&f=geojson`);
  if (!res.ok) throw new Error(`${name}: the layer returned ${res.status}`);
  const data = {
    source: LAYERS[name],
    layer: meta.name,
    edited: meta.editingInfo?.lastEditDate ? new Date(meta.editingInfo.lastEditDate).toISOString().slice(0, 10) : null,
    downloaded: new Date().toISOString().slice(0, 10),
    features: (await res.json()).features,
  };
  writeFileSync(file, JSON.stringify(data));
  console.log(`  downloaded ${name}: ${data.features.length} features (layer edited ${data.edited})`);
  return data;
}

const route = await load("route");
const stations = await load("stations");

const round = (v) => +v.toFixed(5); // about 1 m
const lines = [];
for (const f of route.features) {
  const p = f.properties;
  if (p.Phasing !== "Phase 1" || NOT_PASSENGER.has(p.Extents)) continue;
  const parts = f.geometry.type === "LineString" ? [f.geometry.coordinates] : f.geometry.coordinates;
  for (const part of parts) {
    const slim = part.length > 2 ? simplify(lineString(part), { tolerance: TOLERANCE, highQuality: true }).geometry.coordinates : part;
    lines.push(slim.map(([lng, lat]) => [round(lng), round(lat)]));
  }
}
const stops = stations.features
  .filter((f) => f.properties.PHASE === "Phase 1")
  .map((f) => ({ name: f.properties.NAME, lng: round(f.geometry.coordinates[0]), lat: round(f.geometry.coordinates[1]) }));

const miles = (a, b) => {
  const rad = Math.PI / 180;
  const h = Math.sin(((b[1] - a[1]) * rad) / 2) ** 2 + Math.cos(a[1] * rad) * Math.cos(b[1] * rad) * Math.sin(((b[0] - a[0]) * rad) / 2) ** 2;
  return 2 * 3958.8 * Math.asin(Math.sqrt(h));
};
const length = lines.reduce((a, l) => a + l.slice(1).reduce((s, pt, i) => s + miles(l[i], pt), 0), 0);
// Every station should sit on the line: a station far from it means the two layers disagree.
const offLine = stops
  .map((s) => ({ s, d: Math.min(...lines.map((l) => pointToLineDistance(point([s.lng, s.lat]), lineString(l), { units: "miles" }))) }))
  .filter((x) => x.d > 0.02);

const body = `// GENERATED by scripts/build_light_rail.mjs. Do not edit; run "npm run build:rail".
// Austin Light Rail, Phase 1: the route and stations as published by Austin
// Transit Partnership (ATP). Planned, not built: construction is scheduled
// to start in 2027 and service in 2033.
// What is drawn and what is left out: the notes at the top of that script.

export const LIGHT_RAIL_SOURCE = ${JSON.stringify({
    publisher: "Austin Transit Partnership",
    route: { layer: route.layer, url: route.source, edited: route.edited, downloaded: route.downloaded },
    stations: { layer: stations.layer, url: stations.source, edited: stations.edited, downloaded: stations.downloaded },
    miles: +length.toFixed(1),
  }, null, 2)};

// One line in several pieces (trunk, the two branches and their junction). [lng, lat]
export const PROJECT_CONNECT_LINES = [
${lines.map((l) => `  { name: "Austin Light Rail, Phase 1", color: "#2563eb", coords: ${JSON.stringify(l)} },`).join("\n")}
];

export const LIGHT_RAIL_STATIONS = [
${stops.map((s) => `  ${JSON.stringify(s)},`).join("\n")}
];
`;
writeFileSync(OUT, body);
console.log(`Route: ${lines.length} pieces, ${lines.reduce((a, l) => a + l.length, 0)} points, ${length.toFixed(2)} miles | stations: ${stops.length}`);
console.log(offLine.length ? `Stations more than 100 feet from the line: ${offLine.map((x) => `${x.s.name} (${Math.round(x.d * 5280)} ft)`).join(", ")}` : "Every station is within 100 feet of the line.");
console.log(`Wrote data/projectConnect.js (${(body.length / 1024).toFixed(1)} KB)`);
