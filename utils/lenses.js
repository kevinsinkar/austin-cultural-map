// ── The three Triage lenses (presenter mode only) ──
//
// Each lens asks one question of the same displacement stages the map shows
// (utils/stages.js) and adds one or two measured figures. A lens sorts every
// census tract into a group by a stated rule. There is no composite score and
// no weighting: every figure is either a census figure, a count, or a
// z-score built the way the stage tests build theirs.
//
//   Trajectory  where is change moving now?
//   Equity      where do vulnerable residents live, and where has
//               Preservation Austin's recorded work been?
//   Matrix      who lives here, and what is the housing market doing?
//
// Figures for the latest survey come from data/stageLenses.js, generated by
// scripts/build_stages.mjs. Method: DATA_METHODOLOGY.md, section 6.

