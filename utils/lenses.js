export const LENS_BY_KEY = Object.fromEntries(LENSES.map((l) => [l.key, l]));

/** How the Preservation Austin listings are placed: all, with a place, and area-only. */
export const PA_LISTING_COUNTS = {
  all: PA_ALL.length,
  placed: PA_PLACED.length,
  areaOnly: PA_PLACED.filter((i) => !/\d/.test(i.address || "")).length,
};

function trajectoryGroup(r) {
  if (!r.scored) return "unscored";
  if (r.cls === "loss") return r.cls2015 === "loss" ? "lossEarlier" : "lossRecent";
  if (r.cls === "vulnerable") return r.recent === true ? "starting" : "holding";
  if (ACTIVE.has(r.cls)) return r.recent === true ? "shifting" : "activeQuiet";
  return "none";
}

function equityGroup(r) {
  if (!r.scored) return "unscored";
  if (RESIDENTS_VULNERABLE.has(r.cls)) return r.paNear > 0 ? "riskReached" : "riskGap";
  if (r.cls === "loss") return r.paNear > 0 ? "lossReached" : "lossGap";
  return "none";
}

function matrixGroup(r) {
  if (!r.scored) return "unscored";
  const fast = r.riseHigh === true;
  if (r.vulnerableNow) return fast ? "pressure" : "exposed";
  if (fast) return r.vulnerable2000 === true ? "changed" : "rising";
  return "neither";
}

// ── One row per census tract ──

const measure = (stage, key) => stage?.vulnerable?.measures.find((m) => m.key === key)?.value ?? null;

function buildRow(region) {
  const id = region.region_id;
  const place = tractPlace(id);
  const series = stageSeriesFor({ kind: "tract", id });
  const byYear = Object.fromEntries(series.map((s) => [s.dataYear, s]));
  const now = byYear[LATEST];
  if (!place || !now) return null;
  const base = byYear[STAGE_BASE_YEAR];
  const lens = TRACT_LENS_ROWS[id] || [];
  const at = (f) => lens[LT[f]] ?? null;
  const flag = (f) => (at(f) == null ? null : at(f) === 1);
  const measured = calcDirectDisplacement(id);
  const biz = businessesIn([id]);
  const pocThen = measure(base, "poc");
  const pocNow = measure(now, "poc");

  const row = {
    regionId: id,
    name: place.title,
    tract: tractNumber(id),
    scored: now.scored,
    cls: now.cls.key,
    stage: now,
    path: PATH_YEARS.map((y) => ({ year: y, cls: byYear[y]?.cls || null })),
    cls2015: byYear[EARLIER]?.cls.key || null,
    population: now.population,

    // Test 1, now and in 2000
    vulnerableNow: now.vulnerable?.yes ?? null,
    vCount: now.vulnerable?.count ?? null,
    vulnerable2000: base?.scored ? base.code === "V0" : null,
    pocThen,
    pocNow,
    pocDelta: pocThen != null && pocNow != null ? +(pocNow - pocThen).toFixed(1) : null,
    bhDelta: measured?.bhDelta ?? null,
    bhFromYear: measured?.fromYear ?? null,

    // Test 2 since 2000, and the same test between the two latest surveys
    changed: now.change?.measured ? now.change.yes : null,
    dIndex: at("dIndex"),
    recent: flag("recent"),
    rIndex: at("rIndex"),
    recentMeasures: ["owner", "white", "ba", "mfi"].map((k, i) => ({
      key: k, value: at(`r_${k}`), over: !!((at("rBits") || 0) & (1 << i)),
    })),
    carried: at("carried") === 1,

    // Test 3
    housing: now.housing,
    riseHigh: now.housing ? now.housing.riseHigh : null,
    risePct: at("risePct"),
    recentRise: at("recentRise"),
    recentHigh: flag("recentHigh"),

    // What is on record here
    paNear: paNearTracts([id]).length,
    bizOpen: biz.open.length,
    bizClosed: biz.closed.length,
  };
  row.groups = { trajectory: trajectoryGroup(row), equity: equityGroup(row), matrix: matrixGroup(row) };
  return row;
}

let rowsCache = null;
/** Every census tract on the map, with the figures all three lenses use. */
export function lensRows() {
  if (!rowsCache) rowsCache = REGION_INDEX.map(buildRow).filter(Boolean);
  return rowsCache;
}

/** { groupKey: count } for a lens. */
export function groupCounts(lensKey, rows = lensRows()) {
  const out = Object.fromEntries(LENS_BY_KEY[lensKey].groups.map((g) => [g.key, 0]));
  for (const r of rows) out[r.groups[lensKey]]++;
  return out;
}

const plural = (n, one, many) => `${n} ${n === 1 ? one : many}`;

/** Plain sentences stating what a lens finds. Counts only; no place is ranked. */
export function lensSummary(lensKey, rows = lensRows()) {
  const c = groupCounts(lensKey, rows);
  if (lensKey === "trajectory") {
    const moving = c.starting + c.shifting;
    const recentOnly = rows.filter((r) => ["starting", "shifting"].includes(r.groups.trajectory) && r.changed === false).length;
    return [
      `${plural(moving, "tract", "tracts")} where vulnerable residents live show a population shift between the 2011–2015 and 2019–2023 surveys. In ${recentOnly} of them the longer test, since 2000, shows no change: the shift is recent.`,
      `${plural(c.lossRecent, "tract has", "tracts have")} moved into continued loss since the 2011–2015 survey; ${c.lossEarlier} were already there.`,
      `${plural(c.holding, "vulnerable tract shows", "vulnerable tracts show")} no shift between the two surveys.`,
    ];
  }
  if (lensKey === "equity") {
    const risk = c.riskGap + c.riskReached;
    const loss = c.lossGap + c.lossReached;
    const noneNear = rows.filter((r) => r.groups.equity === "none" && r.paNear > 0).length;
    return [
      `Vulnerable residents live in ${plural(risk, "tract", "tracts")} (Vulnerable, Early, Dynamic or Late). ${c.riskReached} of them ${c.riskReached === 1 ? "has" : "have"} a Preservation Austin listing nearby.`,
      `Of the ${plural(loss, "tract", "tracts")} in continued loss, ${c.lossReached} ${c.lossReached === 1 ? "has" : "have"} a listing nearby. Of the ${c.none} with no stage, ${noneNear} do.`,
      `${PA_PLACED.length} listings that name a place are counted. A listing is "nearby" within about 1.3 km of a tract's center.`,
    ];
  }
  return [
    `In ${plural(c.pressure, "tract", "tracts")} vulnerable residents live where home values are rising fast. In ${c.exposed} they live where values are not rising fast.`,
    `${plural(c.changed, "tract was", "tracts were")} vulnerable in 2000, no longer ${c.changed === 1 ? "is" : "are"}, and ${c.changed === 1 ? "has" : "have"} fast-rising values.`,
    `${c.rising} more have fast-rising values without vulnerable residents now or in 2000.`,
  ];
}

/** How many tracts carry 2011–2015 figures estimated from earlier boundaries. */
export function carriedCount(rows = lensRows()) {
  return rows.filter((r) => r.carried).length;
}
